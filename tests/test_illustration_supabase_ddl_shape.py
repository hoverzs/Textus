def test_server_trust_auth_model_documented_not_rls_user_auth() -> None:
    """Pins the auth-model correction: this migration's header must
    explicitly say server-trust, and no `create policy`/RPC in this file
    may actually GATE anything on `auth.uid()` (the header note is
    allowed to mention it explanatorily -- to say why it is NOT used)."""
    assert "SERVER-TRUST" in DDL_SQL
    assert "service_role bypasses" in DDL_SQL.lower() or "service_role` bypasses" in DDL_SQL
    # No policy anywhere (already asserted above) means auth.uid() cannot
    # be gating any RLS policy; and the RPC body itself never references it.
    rpc_start = DDL_SQL.index("create or replace function get_published_illustration_candidates")
    rpc_end = DDL_SQL.index("$$;", rpc_start)
    assert "auth.uid()" not in DDL_SQL[rpc_start:rpc_end]
