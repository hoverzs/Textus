def test_production_rpc_rechecks_license_and_status_itself() -> None:
    """Never trust the publish-time trigger alone -- the RPC re-derives
    the exact same filter on every call (2026-09-13 architecture
    decision: a source retroactively marked restricted must immediately
    stop surfacing its previously-published units)."""
    rpc_start = DDL_SQL.index("create or replace function get_published_illustration_candidates")
    rpc_body = DDL_SQL[rpc_start:]
    assert "u.status = 'published'" in rpc_body
    assert "s.license_status in (" in rpc_body


def test_production_rpc_never_exposes_admin_or_reviewer_fields() -> None:
    rpc_start = DDL_SQL.index("create or replace function get_published_illustration_candidates")
    rpc_end = DDL_SQL.index("$$;", rpc_start)
    rpc_body = DDL_SQL[rpc_start:rpc_end]
    for forbidden in ("qa_issues", "qa_confidence", "enrichment_model", "enrichment_warnings", "reviewed_by"):
        assert forbidden not in rpc_body, f"production RPC must never select {forbidden}"


