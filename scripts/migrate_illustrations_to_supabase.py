# ---------------------------------------------------------------------------
# Chunked idempotent upsert with bounded retry -- matches the established
# scripts/import_greek_syntax_to_supabase.py pattern (PostgREST client,
# batched, retried with exponential backoff), NOT a single wrapping DB
# transaction -- see the Phase 1 report §8 for why that pattern was
# chosen over a raw psycopg2 connection or a single migration RPC.
# ---------------------------------------------------------------------------


def _chunks(items: list, size: int):
    for i in range(0, len(items), size):
        yield items[i : i + size]


def _with_retry(fn, *, attempts: int = DEFAULT_RETRY_ATTEMPTS, base_delay: float = DEFAULT_RETRY_BASE_DELAY, description: str = ""):
    last_exc: Exception | None = None
    for attempt in range(attempts):
        try:
            return fn()
        except Exception as exc:  # noqa: BLE001 -- retried broadly, re-raised if exhausted
            last_exc = exc
            if attempt == attempts - 1:
                raise
            delay = base_delay * (2**attempt)
            print(f"  retry {attempt + 1}/{attempts} after error ({description}): {exc} -- sleeping {delay:.1f}s")
            time.sleep(delay)
    raise last_exc  # pragma: no cover -- unreachable, loop always returns or raises


class SupabaseMigrationWriter:
    """Thin wrapper over a `supabase.Client` -- upsert-only, chunked,
    retried. Never issues a DELETE against anything. `on_conflict` names
    each table's natural unique constraint, matching the DDL exactly."""

    def __init__(self, client, *, batch_size: int = DEFAULT_BATCH_SIZE) -> None:
        self.client = client
        self.batch_size = batch_size

    def upsert(self, table: str, rows: list[dict], *, on_conflict: str) -> int:
        written = 0
        for chunk in _chunks(rows, self.batch_size):
            _with_retry(
                lambda chunk=chunk: self.client.table(table).upsert(chunk, on_conflict=on_conflict).execute(),
                description=f"upsert {table} ({len(chunk)} rows)",
            )
            written += len(chunk)
            print(f"  upserted {len(chunk)} row(s) into {table} (running total: {written}/{len(rows)})")
        return written

    def reset_sequences(self) -> None:
        _with_retry(
            lambda: self.client.rpc("reset_illustration_sequences", {}).execute(),
            description="reset_illustration_sequences RPC",
        )
        print("  sequences reset to MAX(id)+1 for all identity-PK tables")


NATURAL_KEYS = {
    "illustration_sources": "code",
    "illustration_stories": "source_id,canonical_key",
    "illustration_units": "story_id,unit_index",
    "illustration_tags": "category,slug",
    "illustration_unit_tags": "unit_id,tag_id",
    "illustration_qa_repairs": "id",  # no natural key beyond the migrated SQLite id itself
    "illustration_import_meta": "key",
    "illustration_enrichment_runs": "id",
    "illustration_enrichment_run_items": "run_id,story_id",
}


def run_migration(source_path: Path, *, apply: bool, supabase_client=None, batch_size: int = DEFAULT_BATCH_SIZE) -> int:
    report = build_readiness_report(source_path)
    print(report.render())

    if not apply:
        print("\n--dry-run (default) -- no Supabase write attempted. Pass --apply to write.")
        return 0 if report.ready_for_apply else 1

    if not report.ready_for_apply:
        print("\nABORTED: readiness checks failed -- refusing to --apply. Fix the FAIL items above first.")
        return 1

    conn = open_source_readonly(source_path)
    try:
        payloads = {
            "illustration_sources": extract_sources(conn),
            "illustration_stories": extract_stories(conn),
            "illustration_units": extract_illustration_units(conn),
            "illustration_tags": extract_tags(conn),
            "illustration_unit_tags": extract_illustration_unit_tags(conn),
            "illustration_qa_repairs": extract_qa_repairs(conn),
            "illustration_import_meta": extract_import_meta(conn),
            "illustration_enrichment_runs": extract_enrichment_runs(conn),
            "illustration_enrichment_run_items": extract_enrichment_run_items(conn),
        }
    finally:
        conn.close()

    if supabase_client is None:
        # 2026-09-13 production incident fix: this MUST be the service_role
        # client, never supabase_client.get_supabase_client() (the anon/
        # publishable client every other read path in this repo uses) --
        # illustration_* tables have zero anon/authenticated grants by
        # design (see the DDL migration's RLS section), so an anon-tier
        # client's first INSERT is correctly rejected by Postgres with
        # "permission denied for table ...". Reuses the project's one
        # existing service-role credential loader rather than duplicating
        # its URL/key resolution here -- see that module's docstring for
        # why this is a DIFFERENT function from the reviewer-gated one.
        from illustration_engine.supabase_review_client import get_service_role_client_for_migration

        supabase_client = get_service_role_client_for_migration()

    writer = SupabaseMigrationWriter(supabase_client, batch_size=batch_size)
    print("\n=== Applying migration ===")
    for table, rows in payloads.items():
        print(f"\n{table}: {len(rows)} row(s)")
        writer.upsert(table, rows, on_conflict=NATURAL_KEYS[table])

    print("\nResetting identity sequences...")
    writer.reset_sequences()

    print("\nMigration apply complete. Run the migration's own post-apply verification "
          "(row-count + spot-check comparison against the source) before treating Supabase "
          "as authoritative.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True, help="Path to the source illustrations.sqlite3 (opened read-only).")
    parser.add_argument("--apply", action="store_true", help="Actually write to Supabase. Without this flag, runs in --dry-run mode.")
    parser.add_argument("--batch-size", type=int, default=DEFAULT_BATCH_SIZE)
    args = parser.parse_args()

    return run_migration(args.source, apply=args.apply, batch_size=args.batch_size)


if __name__ == "__main__":
    sys.exit(main())
