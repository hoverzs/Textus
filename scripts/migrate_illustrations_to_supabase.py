"""One-time, idempotent SQLite -> Supabase migration for the illustration
corpus (Phase 1, 2026-09-13).

Ports every row from the local `illustrations.sqlite3` (schema v6) into
the Supabase tables created by `supabase/migrations/
20260913120000_illustration_corpus_layer.sql`. Preserves every original
SQLite integer id verbatim (the DDL's `generated by default as identity`
strategy makes this possible -- no id-remapping table needed anywhere in
this script).

SAFETY:
- The source SQLite connection is ALWAYS opened `mode=ro` (URI read-only)
  -- this script cannot write to the source database even if it tried.
- `--dry-run` is the DEFAULT. It reads the source, runs every readiness
  check, prints a report ending in `READY_FOR_APPLY=true|false`, and
  exits WITHOUT touching Supabase at all (no network call is even made).
- `--apply` is required, explicitly, to write anything. It still refuses
  to run if any readiness check failed.
- Every write is an upsert against each table's natural unique
  constraint -- re-running `--apply` after a partial failure is safe and
  produces the same end state, never a duplicate row.
- This script NEVER deletes anything, in Supabase or in the source
  SQLite file.

USAGE:
    python scripts/migrate_illustrations_to_supabase.py --source PATH          # dry-run (default)
    python scripts/migrate_illustrations_to_supabase.py --source PATH --apply  # real write

This script has NOT been run in --apply mode against any real Supabase
project as of this commit -- see the Phase 1 report for what still needs
independent review first (SAFE TO RUN MIGRATION --apply: NO until the
generated DDL and a dry-run report have been reviewed).
"""

from __future__ import annotations

import argparse
import hashlib
import sqlite3
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

DEFAULT_BATCH_SIZE = 200
DEFAULT_RETRY_ATTEMPTS = 5
DEFAULT_RETRY_BASE_DELAY = 0.5

PUBLISHABLE_LICENSE_STATUSES = frozenset(
    {"public_domain_confirmed", "public_domain_assumed_by_age", "permission_granted"}
)
ALLOWED_STORY_STATUSES = frozenset({"draft", "needs_review", "approved", "published"})
ALLOWED_UNIT_STATUSES = ALLOWED_STORY_STATUSES
ALLOWED_DERIVATION_TYPES = frozenset(
    {"full_story_translation", "condensed_story", "extracted_scene"}
)
ALLOWED_ADAPTATION_STATUSES = frozenset(
    {"verbatim_transcription", "modernized_spelling", "editorial_paraphrase"}
)
ALLOWED_NARRATIVE_STATUSES = frozenset(
    {
        "documented_historical_event", "legend_about_historical_figure", "traditional_anecdote",
        "fable", "folktale", "rabbinic_aggadic_tale", "didactic_tale",
    }
)
ALLOWED_QA_STATUSES = frozenset({"pending", "passed", "needs_attention", "failed"})
ALLOWED_TAG_CATEGORIES = frozenset({"topic", "tone", "function"})

# Migration order matters -- FK-dependency order, parents before children.
SOURCE_TABLES = (
    "sources", "stories", "illustration_units", "tags", "illustration_unit_tags",
    "qa_repairs", "import_meta", "enrichment_runs", "enrichment_run_items",
)


# ---------------------------------------------------------------------------
# Readiness checks (dry-run — no network access, pure SQLite reads)
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class CheckResult:
    name: str
    passed: bool
    detail: str = ""


@dataclass
class MigrationReadinessReport:
    source_path: Path
    row_counts: dict[str, int]
    checks: list[CheckResult] = field(default_factory=list)

    @property
    def ready_for_apply(self) -> bool:
        return bool(self.checks) and all(c.passed for c in self.checks)

    def render(self) -> str:
        lines = [f"=== Illustration migration readiness report: {self.source_path} ==="]
        lines.append(f"Row counts: {self.row_counts}")
        lines.append("")
        for c in self.checks:
            status = "PASS" if c.passed else "FAIL"
            lines.append(f"[{status}] {c.name}" + (f" -- {c.detail}" if c.detail else ""))
        lines.append("")
        lines.append(f"READY_FOR_APPLY={'true' if self.ready_for_apply else 'false'}")
        return "\n".join(lines)


def open_source_readonly(path: Path) -> sqlite3.Connection:
    """Always mode=ro -- this connection structurally cannot write,
    regardless of what the rest of this script does or any bug in it."""
    if not path.exists():
        raise FileNotFoundError(f"source SQLite DB not found: {path}")
    conn = sqlite3.connect(path.as_uri() + "?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    return conn


def row_counts(conn: sqlite3.Connection) -> dict[str, int]:
    return {t: conn.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0] for t in SOURCE_TABLES}


def check_sqlite_integrity(conn: sqlite3.Connection) -> CheckResult:
    result = conn.execute("PRAGMA integrity_check").fetchone()[0]
    return CheckResult("sqlite_integrity_check", result == "ok", result)


def check_foreign_key_integrity(conn: sqlite3.Connection) -> CheckResult:
    violations = conn.execute("PRAGMA foreign_key_check").fetchall()
    return CheckResult(
        "sqlite_foreign_key_check", len(violations) == 0, f"{len(violations)} violation(s)"
    )


def check_duplicate_natural_keys(conn: sqlite3.Connection) -> list[CheckResult]:
    results = []

    def _dup(name: str, query: str) -> None:
        rows = conn.execute(query).fetchall()
        results.append(CheckResult(name, len(rows) == 0, f"{len(rows)} duplicate group(s)"))

    _dup("sources.code unique", "SELECT code, COUNT(*) c FROM sources GROUP BY code HAVING c > 1")
    _dup(
        "stories.(source_id,canonical_key) unique",
        "SELECT source_id, canonical_key, COUNT(*) c FROM stories "
        "GROUP BY source_id, canonical_key HAVING c > 1",
    )
    _dup(
        "illustration_units.(story_id,unit_index) unique",
        "SELECT story_id, unit_index, COUNT(*) c FROM illustration_units "
        "GROUP BY story_id, unit_index HAVING c > 1",
    )
    _dup(
        "tags.(category,slug) unique",
        "SELECT category, slug, COUNT(*) c FROM tags GROUP BY category, slug HAVING c > 1",
    )
    return results


def check_story_checksums(conn: sqlite3.Connection) -> CheckResult:
    rows = conn.execute(
        "SELECT id, original_text, original_text_checksum FROM stories "
        "WHERE original_text_checksum IS NOT NULL"
    ).fetchall()
    mismatches = [
        row["id"]
        for row in rows
        if hashlib.sha256(row["original_text"].encode("utf-8")).hexdigest()
        != row["original_text_checksum"]
    ]
    return CheckResult(
        "story original_text checksum verification",
        len(mismatches) == 0,
        f"{len(mismatches)} mismatch(es)" + (f": {mismatches[:10]}" if mismatches else ""),
    )


def check_tag_junction_integrity(conn: sqlite3.Connection) -> CheckResult:
    orphan_units = conn.execute(
        "SELECT COUNT(*) FROM illustration_unit_tags ut "
        "WHERE NOT EXISTS (SELECT 1 FROM illustration_units u WHERE u.id = ut.unit_id)"
    ).fetchone()[0]
    orphan_tags = conn.execute(
        "SELECT COUNT(*) FROM illustration_unit_tags ut "
        "WHERE NOT EXISTS (SELECT 1 FROM tags t WHERE t.id = ut.tag_id)"
    ).fetchone()[0]
    ok = orphan_units == 0 and orphan_tags == 0
    return CheckResult(
        "illustration_unit_tags junction integrity",
        ok,
        f"{orphan_units} orphan unit_id ref(s), {orphan_tags} orphan tag_id ref(s)",
    )


def check_enum_values(conn: sqlite3.Connection) -> list[CheckResult]:
    results = []

    def _enum(name: str, query: str, allowed: frozenset[str]) -> None:
        rows = conn.execute(query).fetchall()
        bad = [r[0] for r in rows if r[0] is not None and r[0] not in allowed]
        results.append(CheckResult(name, len(bad) == 0, f"unexpected: {bad[:10]}" if bad else ""))

    _enum("stories.status enum", "SELECT DISTINCT status FROM stories", ALLOWED_STORY_STATUSES)
    _enum(
        "stories.adaptation_status enum",
        "SELECT DISTINCT adaptation_status FROM stories",
        ALLOWED_ADAPTATION_STATUSES,
    )
    _enum(
        "illustration_units.status enum",
        "SELECT DISTINCT status FROM illustration_units",
        ALLOWED_UNIT_STATUSES,
    )
    _enum(
        "illustration_units.derivation_type enum",
        "SELECT DISTINCT derivation_type FROM illustration_units",
        ALLOWED_DERIVATION_TYPES,
    )
    _enum(
        "illustration_units.narrative_status enum",
        "SELECT DISTINCT narrative_status FROM illustration_units",
        ALLOWED_NARRATIVE_STATUSES,
    )
    _enum(
        "illustration_units.qa_status enum",
        "SELECT DISTINCT qa_status FROM illustration_units",
        ALLOWED_QA_STATUSES,
    )
    _enum("tags.category enum", "SELECT DISTINCT category FROM tags", ALLOWED_TAG_CATEGORIES)
    return results


def check_publish_state_invariants(conn: sqlite3.Connection) -> list[CheckResult]:
    results = []
    bad_content = conn.execute(
        "SELECT COUNT(*) FROM illustration_units WHERE status='published' AND "
        "(title_hu IS NULL OR modern_hu_text IS NULL OR summary_hu IS NULL OR human_reviewed_at IS NULL)"
    ).fetchone()[0]
    results.append(
        CheckResult(
            "published units have complete content + human_reviewed_at",
            bad_content == 0,
            f"{bad_content} violating row(s)",
        )
    )

    publishable_list = ",".join(f"'{s}'" for s in sorted(PUBLISHABLE_LICENSE_STATUSES))
    bad_license = conn.execute(
        f"""
        SELECT COUNT(*) FROM illustration_units u
        JOIN stories st ON st.id = u.story_id JOIN sources s ON s.id = st.source_id
        WHERE u.status = 'published' AND s.license_status NOT IN ({publishable_list})
        """
    ).fetchone()[0]
    results.append(
        CheckResult(
            "published units have publishable source license",
            bad_license == 0,
            f"{bad_license} violating row(s)",
        )
    )
    return results


def build_readiness_report(source_path: Path) -> MigrationReadinessReport:
    conn = open_source_readonly(source_path)
    try:
        checks = [check_sqlite_integrity(conn), check_foreign_key_integrity(conn)]
        checks.extend(check_duplicate_natural_keys(conn))
        checks.append(check_story_checksums(conn))
        checks.append(check_tag_junction_integrity(conn))
        checks.extend(check_enum_values(conn))
        checks.extend(check_publish_state_invariants(conn))
        return MigrationReadinessReport(
            source_path=source_path, row_counts=row_counts(conn), checks=checks
        )
    finally:
        conn.close()


