    rows = conn.execute("SELECT * FROM sources").fetchall()
    return [
        {
            "id": r["id"], "code": r["code"], "title": r["title"], "author": r["author"],
            "orig_language": r["orig_language"], "publication_year": r["publication_year"],
            "edition_reference": r["edition_reference"], "license_status": r["license_status"],
            "license_basis_hu": r["license_basis_hu"], "rights_holder": r["rights_holder"],
            "source_url": r["source_url"], "retrieved_at": r["retrieved_at"],
            "reliability_tier": r["reliability_tier"], "notes_hu": r["notes_hu"],
            "tradition": r["tradition"], "registered_at": r["registered_at"],
        }
        for r in rows
    ]


