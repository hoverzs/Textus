def extract_illustration_units(conn: sqlite3.Connection) -> list[dict]:
    import json

    rows = conn.execute("SELECT * FROM illustration_units").fetchall()
    out = []
    for r in rows:
        warnings = json.loads(r["enrichment_warnings_json"]) if r["enrichment_warnings_json"] else None
        issues = json.loads(r["qa_issues_json"]) if r["qa_issues_json"] else None
        out.append(
            {
                "id": r["id"], "story_id": r["story_id"], "unit_index": r["unit_index"],
                "derivation_type": r["derivation_type"],
                "source_span_start": r["source_span_start"], "source_span_end": r["source_span_end"],
                "title_hu": r["title_hu"], "modern_hu_text": r["modern_hu_text"],
                "summary_hu": r["summary_hu"], "moral_hu": r["moral_hu"],
                "narrative_status": r["narrative_status"],
                "narrative_status_confidence": r["narrative_status_confidence"],
                "status": r["status"], "enrichment_model": r["enrichment_model"],
                "enrichment_prompt_version": r["enrichment_prompt_version"],
                "enrichment_generated_at": r["enrichment_generated_at"],
                "enrichment_warnings": warnings,
                "qa_status": r["qa_status"], "qa_model": r["qa_model"],
                "qa_prompt_version": r["qa_prompt_version"], "qa_checked_at": r["qa_checked_at"],
                "qa_confidence": r["qa_confidence"], "qa_issues": issues,
                "human_reviewed_at": r["human_reviewed_at"],
                # reviewed_by (uuid) intentionally omitted -- no Supabase Auth
                # identity exists for any historical SQLite reviewer action;
                # reviewed_by_email also stays NULL for migrated rows (the
                # SQLite schema never recorded WHO reviewed a unit, only
                # WHEN -- see illustration_sqlite.py's human_reviewed_at
                # column, no reviewer-identity column exists there at all).
                "created_at": r["created_at"], "updated_at": r["updated_at"],
            }
        )
    return out


