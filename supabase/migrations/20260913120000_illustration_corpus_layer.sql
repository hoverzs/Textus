-- ===========================================================================
-- Row Level Security — deny-by-default on every table. See the header
-- note: this is defense in depth, NOT the write path's actual security
-- boundary (the write path is server-trust via a gated service_role
-- client). No policies are defined for anon/authenticated on any of
-- these tables -- every read a public user needs goes through the one
-- narrow RPC below instead.
-- ===========================================================================

-- 2026-09-13 real-PostgreSQL validation finding: service_role does NOT
-- automatically receive base table privileges just by existing -- the
-- established convention in this repo's OWN prior migrations
-- (20260908190000_hebrew_linguistic_layer.sql, 20260911220000_greek_
-- linguistic_layer.sql) EXPLICITLY grants select/insert/update/delete to
-- service_role per table, rather than assuming a platform default. This
-- migration initially omitted that explicit grant (an oversight caught by
-- a local disposable-Postgres validation run, NOT assumed from Supabase's
-- behavior) -- without it, the review write path's service_role client
-- would get "permission denied for table ..." on every write, in a real
-- project exactly as it did in this local test. Fixed to match the
-- established pattern exactly.
do $$
declare
    tbl text;
begin
    for tbl in
        select unnest(array[
            'illustration_sources',
            'illustration_stories',
            'illustration_units',
            'illustration_tags',
            'illustration_unit_tags',
            'illustration_qa_repairs',
            'illustration_import_meta',
            'illustration_enrichment_runs',
            'illustration_enrichment_run_items'
        ])
    loop
        execute format('alter table %I enable row level security;', tbl);
        execute format('revoke all on %I from anon, authenticated;', tbl);
        execute format('grant select, insert, update, delete on %I to service_role;', tbl);
    end loop;
end;
$$;

-- ===========================================================================
-- Production read RPC — the ONLY surface anon/authenticated ever touches.
-- ===========================================================================
--
-- SECURITY DEFINER is required here (unlike the service_role-only Hebrew
-- bundle RPC above, which never needs it because service_role already
-- bypasses RLS regardless of invoker/definer): anon/authenticated hold
-- NO table grants and NO RLS policies on these tables, so a plain
-- (default SECURITY INVOKER) function called by anon would see zero
-- rows. SECURITY DEFINER runs with the function owner's privileges
-- instead, but the function body itself is the only thing that decides
-- what is exposed -- and it re-derives the exact same filter
-- illustration_engine.illustration_sqlite's published_illustration_units
-- SQLite view already enforces (status='published' AND source license
-- publishable), on every single call, never trusting the publish-time
-- trigger alone (Textus architecture decision, 2026-09-13: a source
-- retroactively marked 'restricted' must immediately stop surfacing its
-- previously-published units). `set search_path = public` is required
-- security hygiene for any SECURITY DEFINER function (prevents a
-- search_path-hijack attack).
--
-- Field list is deliberately narrow: title_hu/modern_hu_text/summary_hu/
-- moral_hu/topics/tone/homiletic_functions/source_title/source_code/
-- tradition/license_status -- retrieval.py's RetrievalCandidate shape,
-- nothing more. NEVER qa_issues, qa_confidence, enrichment_model,
-- enrichment_warnings, reviewed_by, reviewed_by_email, or any other
-- admin/reviewer-facing field.
create or replace function get_published_illustration_candidates()
returns table (
    unit_id bigint,
    title_hu text,
    modern_hu_text text,
    summary_hu text,
    moral_hu text,
    topics text[],
    tone text,
    homiletic_functions text[],
    source_title text,
    source_code text,
    tradition text,
    license_status text,
    original_text text,
    original_text_checksum text
)
language sql
stable
security definer
set search_path = public
as $$
    select
        u.id as unit_id,
        u.title_hu,
        u.modern_hu_text,
        u.summary_hu,
        u.moral_hu,
        coalesce(
            (select array_agg(t.slug order by t.slug) from illustration_unit_tags ut
             join illustration_tags t on t.id = ut.tag_id
             where ut.unit_id = u.id and t.category = 'topic'),
            '{}'::text[]
        ) as topics,
        (select t.slug from illustration_unit_tags ut
         join illustration_tags t on t.id = ut.tag_id
         where ut.unit_id = u.id and t.category = 'tone' limit 1) as tone,
        coalesce(
            (select array_agg(t.slug order by t.slug) from illustration_unit_tags ut
             join illustration_tags t on t.id = ut.tag_id
             where ut.unit_id = u.id and t.category = 'function'),
            '{}'::text[]
        ) as homiletic_functions,
        s.title as source_title,
        s.code as source_code,
        s.tradition,
        s.license_status,
        st.original_text,
        st.original_text_checksum
    from illustration_units u
    join illustration_stories st on st.id = u.story_id
    join illustration_sources s on s.id = st.source_id
    where u.status = 'published'
      and s.license_status in ('public_domain_confirmed','public_domain_assumed_by_age','permission_granted');
$$;

revoke all on function get_published_illustration_candidates() from public;
grant execute on function get_published_illustration_candidates() to anon, authenticated;

comment on function get_published_illustration_candidates() is
    'Read-only, SECURITY DEFINER. Re-checks status=published AND source license publishable on every call, independent of the publish-time trigger. Returns only retrieval-relevant fields -- never qa_issues, enrichment provenance, or reviewer identity. Safe for the anon key.';

-- ===========================================================================
-- Post-migration sequence reset — used ONCE by
-- scripts/migrate_illustrations_to_supabase.py's --apply path, after all
-- explicit-id rows have been inserted (see the PRIMARY KEY STRATEGY note
-- at the top of this file). service_role-only: this is an administrative
-- migration operation, never called from the live app.
create or replace function reset_illustration_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    t record;
begin
    for t in
        select unnest(array[
            'illustration_sources', 'illustration_stories', 'illustration_units',
            'illustration_tags', 'illustration_qa_repairs',
            'illustration_enrichment_runs', 'illustration_enrichment_run_items'
        ]) as table_name
    loop
        execute format(
            'select setval(pg_get_serial_sequence(%L, ''id''), coalesce((select max(id) from %I), 1), (select max(id) from %I) is not null)',
            t.table_name, t.table_name, t.table_name
        );
    end loop;
end;
$$;

revoke all on function reset_illustration_sequences() from public, anon, authenticated;
grant execute on function reset_illustration_sequences() to service_role;

comment on function reset_illustration_sequences() is
    'One-time post-migration step: resets every identity sequence to MAX(id) so ordinary new rows created after the bulk explicit-id migration get correct, non-colliding ids. service_role-only, called exactly once by scripts/migrate_illustrations_to_supabase.py --apply.';
