-- Taxonomy review-protection trigger (audit fix ported from the SQLite
-- side, see illustration_engine/illustration_unit_repository.py's
-- replace_review_tags() docstring -- "REVIEW PROTECTION (audit fix,
-- 2026-09-13)"): a unit's tags are content, exactly like title_hu, and
-- must be equally protected once human_reviewed_at is set. Blocks BOTH
-- insert (adding a tag) and delete (removing a tag) on an already-
-- reviewed unit -- the caller must demote the unit (clear
-- human_reviewed_at, reset status to needs_review) first. This is the
-- DB-layer half of the guarantee; the Python-side service-role review
-- repository (Phase 1 skeleton) enforces the identical rule before ever
-- issuing the write, for a clearer error message -- same "Python check
-- for UX, DB trigger for the actual fail-closed guarantee" split as
-- every other gate in this schema.
create or replace function trg_illustration_unit_tags_protect_reviewed() returns trigger as $$
declare
    v_unit_id bigint := coalesce(new.unit_id, old.unit_id);
    v_human_reviewed_at timestamptz;
begin
    select human_reviewed_at into v_human_reviewed_at
    from illustration_units where id = v_unit_id;

    if v_human_reviewed_at is not null then
        raise exception 'review_gate: unit % taxonomy is protected (human_reviewed_at=%) -- call send_back_for_rework first', v_unit_id, v_human_reviewed_at;
    end if;
    return coalesce(new, old);
end;
$$ language plpgsql;

create trigger illustration_unit_tags_protect_reviewed
    before insert or delete on illustration_unit_tags
    for each row execute function trg_illustration_unit_tags_protect_reviewed();

